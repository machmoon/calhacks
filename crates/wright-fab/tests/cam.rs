#[test]
fn ffd_matches_the_aircraft_bom() {
    // CS-525 1 m tubes "cut to 974, 974, 540, 540 mm", 4 bought
    let sk = StockKind { id: "cs525".into(), name: "10 mm tube x 1 m".into(), length_mm: 1000.0, od_mm: 10.0, qty_bought: 4, material: "carbon fibre".into(), kerf_mm: 1.5 };
    let cuts = [974.0, 974.0, 540.0, 540.0].iter().enumerate().map(|(i, &l)| Cut { label: format!("c{i}"), length_mm: l }).collect();
    let p = cut::plan(vec![(sk, cuts)]);
    assert_eq!(p.bars.len(), 4, "540 + 540 + 2 kerfs > 1000, so no two cuts share a bar");
    assert!(p.unplaced.is_empty());
    // a cut longer than the bar is reported, not dropped
    let sk = StockKind { id: "t".into(), name: "t".into(), length_mm: 1829.0, od_mm: 150.0, qty_bought: 1, material: "6061".into(), kerf_mm: 2.0 };
    let p = cut::plan(vec![(sk, vec![Cut { label: "tank".into(), length_mm: 2714.0 }])]);
    assert_eq!(p.unplaced.len(), 1);
}

#[test]
fn bom_note_cuts_and_lengths() {
    let bom = "category,id,name,qty,unit,unit_price_usd,total_usd,url,note\n\
tubes,cst_cs525_1m,CST - The Composites Store CS-525 1M DPP Carbon Fiber Tube 10 mm OD x 8 mm ID x 1 m,4,tubes,16.15,64.60,http://x,\"cut to 974, 974, 540, 540 mm\"\n\
tubes,goodwinds_pct500024,\"Goodwinds PCT .500\"\" x 24\"\" Pultruded Carbon Tube (SKU PCT500024)\",1,tubes,27.29,27.29,https://x,cut to 300 mm\n";
    let g = cut::from_bom(bom);
    assert_eq!(g.len(), 2);
    assert_eq!(g[0].0.length_mm, 1000.0);
    assert_eq!(g[0].0.od_mm, 10.0);
    assert_eq!(g[0].1.len(), 4);
    assert!((g[1].0.length_mm - 609.6).abs() < 0.01, "{}", g[1].0.length_mm);
}

#[test]
fn prusaslicer_layers_roles_and_time() {
    let g = "; generated by PrusaSlicer\nM83\n;LAYER_CHANGE\n;Z:0.2\n;HEIGHT:0.2\nG1 Z.2 F7800\nG1 X0 Y0\n;TYPE:External perimeter\n;WIDTH:0.45\nG1 F1200\nG1 X10 Y0 E0.5\nG1 X10 Y10 E0.5\n;LAYER_CHANGE\n;Z:0.4\n;HEIGHT:0.2\nG1 Z.4\n;TYPE:Internal infill\nG1 X0 Y10 E0.5\n; filament used [g] = 1.25\n; estimated printing time (normal mode) = 1m 0s\n";
    let p = wright_fab::print::parse(g);
    assert_eq!(p.layers, 2);
    assert_eq!(p.segs.len(), 3);
    assert_eq!(p.segs[0].layer, 0);
    assert_eq!(p.segs[2].layer, 1);
    assert_eq!(p.grams, Some(1.25));
    let t: f64 = p.segs.iter().map(|s| s.minutes).sum();
    assert!((t - 1.0).abs() < 1e-9, "move times scaled to the slicer's estimate: {t}");
    assert_ne!(p.segs[0].role, p.segs[2].role);
}

#[test]
fn turning_reaches_the_profile_and_no_further() {
    // 50 mm bar to a 40 mm shoulder then 30 mm, over 60 mm
    let prof = vec![(0.0, 15.0), (30.0, 15.0), (30.0, 20.0), (60.0, 20.0)];
    let ops = lathe::turn_od(lathe::turning_tool(1), 300.0, 1.5, 25.0, &prof, 0.0, 60.0);
    let p = Program {
        name: "t".into(),
        part: "t".into(),
        machine: Machine::Lathe,
        material: "6061".into(),
        density: 2.7,
        stock: Stock::Round { d: 50.0, len: 63.0 },
        setups: vec![Setup { name: "s".into(), flipped: false, ops }],
        notes: vec![],
        qty: 1,
    };
    let mut sim = LatheSim::new(-1.5, 61.5, 25.0, 0.0, 60.0);
    for s in p.steps().iter().filter(|s| !s.rapid) {
        let n = ((s.to - s.from).norm() / 0.1).ceil().max(1.0) as usize;
        for k in 0..=n {
            let q = s.from + (s.to - s.from) * (k as f64 / n as f64);
            sim.stamp(ToolKind::Turning(0.8), q.x, q.z, false);
        }
    }
    let r_at = |u: f64| sim.outer[((u - sim.u0) / sim.res) as usize];
    assert!((r_at(10.0) - 15.0).abs() < 0.05, "small diameter {}", r_at(10.0));
    assert!((r_at(45.0) - 20.0).abs() < 0.05, "shoulder diameter {}", r_at(45.0));
    // nothing below the profile anywhere away from the corner
    for u in [5.0, 20.0, 28.0, 33.0, 50.0, 58.0] {
        assert!(r_at(u) >= lathe::radius_at(&prof, u) - 0.05, "gouge at u={u}: {}", r_at(u));
    }
}

#[test]
fn pocket_removes_its_volume() {
    let mut hf = HeightField::block(0.0, 0.0, 60.0, 60.0, 0.0, 10.0, 0.25);
    let op = mill::pocket("p", mill::end_mill(1, 6.0, "6 mm"), 5000.0, 600.0, &mill::circle(30.0, 30.0, 15.0, 128), &[], 10.0, 6.0, 2.0);
    let p = Program { name: "p".into(), part: "p".into(), machine: Machine::Mill, material: "6061".into(), density: 2.7, stock: Stock::Block { x: 60.0, y: 60.0, z: 10.0 }, setups: vec![Setup { name: "s".into(), flipped: false, ops: vec![op] }], notes: vec![], qty: 1 };
    let mut v = 0.0;
    for s in p.steps().iter().filter(|s| !s.rapid) {
        v += hf.sweep(s.from, s.to, 3.0);
    }
    let want = std::f64::consts::PI * 15.0 * 15.0 * 4.0;
    assert!((v - want).abs() / want < 0.05, "pocket volume {v:.0} vs {want:.0} mm^3");
    // nothing outside the circle was cut
    let i = (2.0 / 0.25) as usize;
    assert_eq!(hf.h[i * hf.nx + i], 10.0);
}

#[test]
fn gcode_dialect() {
    let drill = mill::drill("d", mill::drill_tool(2, 5.0, "5 mm"), &[(0.0, 0.0), (10.0, 0.0)], 0.0, -12.0);
    let p = Program { name: "d".into(), part: "d".into(), machine: Machine::Mill, material: "6061".into(), density: 2.7, stock: Stock::Block { x: 20.0, y: 20.0, z: 12.0 }, setups: vec![Setup { name: "s".into(), flipped: false, ops: vec![drill] }], notes: vec![], qty: 1 };
    let g = p.gcode();
    assert!(g.contains("G21 G17 G90 G40 G49 G80 G94 G54"));
    assert!(g.contains("G98 G83 X0.000 Y0.000 Z-12.000 R2.000"));
    assert!(g.contains("\nX10.000 Y0.000\n"), "later holes ride the modal cycle");
    assert!(g.contains("G80") && g.trim_end().ends_with('%'));
    let lathe = lathe::face(lathe::turning_tool(1), 300.0, 25.0, 0.0, 1.5, 0.0);
    let p = Program { name: "l".into(), part: "l".into(), machine: Machine::Lathe, material: "6061".into(), density: 2.7, stock: Stock::Round { d: 50.0, len: 20.0 }, setups: vec![Setup { name: "s".into(), flipped: false, ops: vec![lathe] }], notes: vec![], qty: 1 };
    let g = p.gcode();
    assert!(g.contains("G18 G7 G21 G90 G95"));
    assert!(g.contains("G96 D2500 S300 M3"));
    assert!(g.contains("G0 X54.000"), "X is written as a diameter (radius 27)");
    let _ = v3(0.0, 0.0, 0.0);
}
